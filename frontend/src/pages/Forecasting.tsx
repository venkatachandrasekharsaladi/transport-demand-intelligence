import { useMemo, useState } from "react";
import { ChartNoAxesCombined, Database, Gauge, Route } from "lucide-react";
import {
  CartesianGrid,
  Legend,
  Line,
  LineChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import { dataService } from "../services/dataService";
import { useDashboardData } from "../hooks/useDashboardData";
import { ErrorState, LoadingState, EmptyState } from "../components/States";
import { Notice, Panel, StatCard, ViewHeader, formatCompact, formatHour, formatNumber } from "../components/Ui";
import type { ForecastData } from "../types/data";

export function Forecasting() {
  const { data, loading, error } = useDashboardData<ForecastData>(dataService.getForecast);
  const [route, setRoute] = useState("all");
  const chartData = useMemo(() => {
    if (!data) return [];
    const aggregate = new Map<string, { transit_timestamp: string; forecast: number }>();
    data.forecast.forEach((row) => {
      const current = aggregate.get(row.transit_timestamp) ?? { transit_timestamp: row.transit_timestamp, forecast: 0 };
      current.forecast += row.predicted_ridership;
      aggregate.set(row.transit_timestamp, current);
    });
    const actual = new Map(data.actual_hourly.map((row) => [row.transit_timestamp, row.actual_ridership]));
    return [...aggregate.values()].map((row) => ({ ...row, actual: actual.get(row.transit_timestamp) ?? null }));
  }, [data]);
  if (loading) return <LoadingState />;
  if (error || !data) return <ErrorState message={error ?? "Forecast data is unavailable."} onRetry={() => window.location.reload()} />;
  const routes = [...new Set(data.forecast.map((row) => row.bus_route))].sort();
  const selectedRows = route === "all" ? data.forecast : data.forecast.filter((row) => row.bus_route === route);
  return (
    <>
      <ViewHeader eyebrow="Forecasting agent" title="24-hour demand forecast" description="Explore recursive route forecasts generated by the persisted Random Forest pipeline and compare the network signal with recent observed demand." generatedAt={data.generated_at} />
      <div className="mb-6 grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        <StatCard label="Model" value="Random Forest" helper="Notebook-derived pipeline" icon={<ChartNoAxesCombined className="h-4 w-4" />} />
        <StatCard label="Validation WAPE" value={`${data.model.metrics.validation.wape_percent.toFixed(2)}%`} helper={`MAE ${formatNumber(data.model.metrics.validation.mae, 1)}`} icon={<Gauge className="h-4 w-4" />} tone="green" />
        <StatCard label="Test observations" value={formatNumber(data.model.metrics.test_observations)} helper={`WAPE ${data.model.metrics.test.wape_percent.toFixed(2)}%`} icon={<Database className="h-4 w-4" />} tone="amber" />
        <StatCard label="Routes in forecast" value={formatNumber(routes.length)} helper="Active routes with positive history" icon={<Route className="h-4 w-4" />} tone="blue" />
      </div>
      <div className="mb-6 grid gap-6 xl:grid-cols-[1.35fr_0.65fr]">
        <Panel title="Network demand trajectory" subtitle="Forecast is network-aggregated; historical line shows the latest 168 observed hours">
          <div className="h-80">
            <ResponsiveContainer width="100%" height="100%">
              <LineChart data={chartData} margin={{ top: 8, right: 8, bottom: 0, left: -18 }}>
                <CartesianGrid stroke="#eef1f5" vertical={false} />
                <XAxis dataKey="transit_timestamp" tickFormatter={formatHour} tickLine={false} axisLine={false} minTickGap={24} tick={{ fontSize: 11, fill: "#94a3b8" }} />
                <YAxis tickLine={false} axisLine={false} tickFormatter={formatCompact} tick={{ fontSize: 11, fill: "#94a3b8" }} />
                <Tooltip labelFormatter={(value) => new Date(value).toLocaleString()} formatter={(value: number, name) => [formatNumber(value), name === "forecast" ? "Forecast" : "Actual"]} />
                <Legend verticalAlign="top" height={30} iconType="circle" />
                <Line dataKey="actual" stroke="#94a3b8" strokeWidth={2} dot={false} connectNulls name="Actual" />
                <Line dataKey="forecast" stroke="#2563eb" strokeWidth={3} dot={false} name="Forecast" />
              </LineChart>
            </ResponsiveContainer>
          </div>
        </Panel>
        <Panel title="Model context" subtitle="Evaluation is sourced from the saved artifact metadata">
          <div className="space-y-4">
            <Metric label="Validation MAE" value={data.model.metrics.validation.mae} />
            <Metric label="Validation RMSE" value={data.model.metrics.validation.rmse} />
            <Metric label="Test bias" value={`${data.model.metrics.test.bias_percent.toFixed(2)}%`} />
            <Notice>{data.explanation}</Notice>
          </div>
        </Panel>
      </div>
      <Panel
        title="Forecast records"
        subtitle="Select a route to inspect its forecast features and predicted ridership"
        action={
          <select value={route} onChange={(event) => setRoute(event.target.value)} className="rounded-lg border border-line bg-white px-3 py-2 text-xs font-semibold text-slate-700 outline-none focus:border-accent">
            <option value="all">All routes</option>
            {routes.map((item) => <option key={item} value={item}>{item}</option>)}
          </select>
        }
      >
        {selectedRows.length === 0 ? <EmptyState message="No forecast rows match this route." /> : (
          <div className="max-h-[440px] overflow-auto">
            <table className="w-full min-w-[700px] text-left text-xs">
              <thead className="sticky top-0 bg-white text-[10px] uppercase tracking-wider text-slate-400">
                <tr><th className="pb-3 pr-4">Timestamp</th><th className="pb-3 pr-4">Route</th><th className="pb-3 pr-4">Predicted ridership</th><th className="pb-3 pr-4">24h lag</th><th className="pb-3">168h lag</th></tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {selectedRows.slice(0, 240).map((row) => (
                  <tr key={`${row.transit_timestamp}-${row.bus_route}`} className="text-slate-600">
                    <td className="py-3 pr-4">{new Date(row.transit_timestamp).toLocaleString()}</td>
                    <td className="py-3 pr-4 font-bold text-ink">{row.bus_route}</td>
                    <td className="py-3 pr-4 font-semibold text-accent">{formatNumber(row.predicted_ridership, 1)}</td>
                    <td className="py-3 pr-4">{formatNumber(row.lag_24h, 1)}</td>
                    <td className="py-3">{formatNumber(row.lag_168h, 1)}</td>
                  </tr>
                ))}
              </tbody>
            </table>
            {selectedRows.length > 240 && <p className="mt-4 text-xs text-slate-400">Showing the first 240 rows in this view. The complete response remains available in the generated JSON.</p>}
          </div>
        )}
      </Panel>
    </>
  );
}

function Metric({ label, value }: { label: string; value: number | string }) {
  return <div className="flex items-center justify-between border-b border-slate-100 pb-3 text-sm"><span className="text-slate-500">{label}</span><strong className="text-ink">{typeof value === "number" ? formatNumber(value, 2) : value}</strong></div>;
}
